test("Pages isolates Windows and Linux architectures and rejects partial matrices", async () => {
	const root = fixture();
	const pages = JSON.parse(readFileSync(join(root, "releases.json"), "utf8"));
	const release = pages[1][0];
	let id = 10;
	const addPlatform = (platform: "linux" | "win32") => {
		for (const arch of ["x64", "arm64"]) {
			const artifact = `Clawdi-${platform}-${arch}${platform === "win32" ? "-unsigned.exe" : ".AppImage"}`;
			release.assets.push({ name: `beta-${platform}-${arch}.yml`, id }, { name: artifact });
			if (platform === "win32") release.assets.push({ name: `${artifact}.blockmap` });
			writeFileSync(
				join(root, `asset-${id}.json`),
				JSON.stringify({
					version: "1.1.0-beta.10",
					path: artifact,
					files: [{ url: artifact, sha512: "hash", size: 1 }],
				}),
			);
			id++;
		}
		writeFileSync(join(root, "releases.json"), JSON.stringify(pages));
	};
	writeFileSync(
		join(root, "bin/gh"),
		`#!/bin/sh
case "$2" in
  */assets/2) cat "$FIXTURE_ROOT/stable.json" ;;
  */assets/1) cat "$FIXTURE_ROOT/metadata.json" ;;
  *releases/assets/*) cat "$FIXTURE_ROOT/asset-\${2##*/}.json" ;;
  *) cat "$FIXTURE_ROOT/releases.json" ;;
esac
`,
		{ mode: 0o700 },
	);
	addPlatform("linux");
	expect((await prepare(root)).code).toBe(0);
	expect(existsSync(join(root, "site/desktop/win32-x64/beta.yml"))).toBe(false);

	addPlatform("win32");
	expect((await prepare(root)).code).toBe(0);
	for (const platform of ["win32", "linux"]) {
		for (const arch of ["x64", "arm64"]) {
			const suffix = platform === "win32" ? "" : `-linux${arch === "arm64" ? "-arm64" : ""}`;
			const metadata = parse(
				readFileSync(join(root, `site/desktop/${platform}-${arch}/beta${suffix}.yml`), "utf8"),
			);
			expect(metadata.files[0].url).toContain(
				`Clawdi-${platform}-${arch}${platform === "win32" ? "-unsigned.exe" : ".AppImage"}`,
			);
		}
	}
	const completeAssets = release.assets;
	release.assets = completeAssets.filter(
		(asset: { name: string }) => asset.name !== "Clawdi-win32-x64-unsigned.exe.blockmap",
	);
	writeFileSync(join(root, "releases.json"), JSON.stringify(pages));
	const missingBlockmap = await prepare(root);
	expect(missingBlockmap.code).not.toBe(0);
	expect(missingBlockmap.error).toContain("Missing NSIS blockmap");
	release.assets = completeAssets.filter(
		(asset: { name: string }) => asset.name !== "beta-win32-arm64.yml",
	);
	writeFileSync(join(root, "releases.json"), JSON.stringify(pages));
	const result = await prepare(root);
	expect(result.code).not.toBe(0);
	expect(result.error).toContain("Incomplete Desktop release");
});

test("Pages rejects regressed or invalid live metadata without emitting deployment output", async () => {
	const root = fixture();
	for (const content of ["version: 9.0.0\n", "invalid metadata\n"]) {
		mkdirSync(join(root, "live/desktop"), { recursive: true });
		writeFileSync(join(root, "live/desktop/latest-mac.yml"), content);
		const result = await prepare(root);
		expect(result.code).not.toBe(0);
		expect(result.output).toBe("");
		expect(result.error).toContain(
			content.startsWith("version:") ? "Refusing to regress" : "Invalid existing",
		);
	}
});
