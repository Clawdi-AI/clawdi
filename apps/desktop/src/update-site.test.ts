import { afterEach, test as bunTest, expect } from "bun:test";
import {
	cpSync,
	existsSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { parse } from "yaml";

const roots: string[] = [];
// The Pages publisher runs on Linux; its fixture implements gh as a POSIX script.
const test = bunTest.skipIf(process.platform === "win32");
afterEach(() => {
	for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

function fixture(missingAsset = false) {
	const root = mkdtempSync(join(tmpdir(), "desktop-update-site-"));
	roots.push(root);
	mkdirSync(join(root, "bin"));
	mkdirSync(join(root, "live"));
	const release = (version: string, prerelease: boolean) => ({
		tag_name: `desktop-v${version}`,
		prerelease,
		draft: false,
		published_at: "2020-01-01T00:00:00Z",
		assets: [
			{ name: prerelease ? "beta-mac.yml" : "latest-mac.yml", id: 1 },
			{ name: prerelease ? "beta-mac-x64.yml" : "latest-mac-x64.yml", id: prerelease ? 1 : 2 },
			...(missingAsset ? [] : [{ name: "Clawdi.zip" }]),
		],
	});
	// Different metadata per request is supplied by the fake gh using the selected asset ID.
	const stable = release("1.0.0", false);
	stable.assets[0] = { name: "latest-mac.yml", id: 2 };
	writeFileSync(
		join(root, "releases.json"),
		JSON.stringify([
			[{ tag_name: "clawdi-cli-v99.0.0", draft: false }, release("1.1.0-beta.2", true)],
			[release("1.1.0-beta.10", true), stable],
		]),
	);
	writeFileSync(
		join(root, "metadata.json"),
		JSON.stringify({
			version: "1.1.0-beta.10",
			path: "Clawdi.zip",
			files: [{ url: "Clawdi.zip", sha512: "hash", size: 1 }],
		}),
	);
	writeFileSync(
		join(root, "stable.json"),
		JSON.stringify({
			version: "1.0.0",
			path: "Clawdi.zip",
			files: [{ url: "Clawdi.zip", sha512: "hash", size: 1 }],
		}),
	);
	writeFileSync(
		join(root, "bin", "gh"),
		'#!/bin/sh\ncase "$2" in\n  */assets/2) cat "$FIXTURE_ROOT/stable.json" ;;\n  *releases/assets/*) cat "$FIXTURE_ROOT/metadata.json" ;;\n  *) cat "$FIXTURE_ROOT/releases.json" ;;\nesac\n',
		{ mode: 0o700 },
	);
	// Stub only the HTTP boundary; run the real generation, guard and comparison.
	writeFileSync(
		join(root, "fetch.ts"),
		`import { appendFileSync, existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
globalThis.fetch = async (input) => {
  const url = new URL(String(input));
  if (url.origin !== "https://example.invalid" || !url.pathname.startsWith("/project/")) throw new Error("Unexpected URL");
  const path = url.pathname.slice("/project/".length);
  appendFileSync(join(process.env.FIXTURE_ROOT, "requests"), path + "\\n");
  if (process.env.HTTP_FAILURE_PATH === path) {
    if (process.env.HTTP_FAILURE === "transport") throw new Error("Network failure");
    return new Response("Unavailable", { status: Number(process.env.HTTP_FAILURE) });
  }
  const file = join(process.env.FIXTURE_ROOT, "live", path);
  return existsSync(file) ? new Response(readFileSync(file)) : new Response("Not found", { status: 404 });
};
`,
	);

	return root;
}

async function prepare(root: string, paused = "", failure = "", failurePath = "") {
	const output = join(root, "github-output");
	rmSync(output, { force: true });
	rmSync(join(root, "requests"), { force: true });
	const child = Bun.spawn(
		[
			process.execPath,
			"--preload",
			join(root, "fetch.ts"),
			resolve(import.meta.dir, "../scripts/prepare-update-site.ts"),
			join(root, "site"),
		],
		{
			env: {
				...process.env,
				PATH: `${join(root, "bin")}:${process.env.PATH}`,
				FIXTURE_ROOT: root,
				GITHUB_REPOSITORY: "owner/repo",
				DESKTOP_PAUSED_VERSIONS: paused,
				DESKTOP_UPDATE_SITE_URL: "https://example.invalid/project/",
				GITHUB_OUTPUT: output,
				HTTP_FAILURE: failure,
				HTTP_FAILURE_PATH: failurePath,
			},
			stdout: "pipe",
			stderr: "pipe",
		},
	);
	return {
		code: await child.exited,
		error: await new Response(child.stderr).text(),
		output: existsSync(output) ? readFileSync(output, "utf8") : "",
	};
}

test("Pages skips identical prepared content, including other site files", async () => {
	const root = fixture();
	expect((await prepare(root)).code).toBe(0);
	mkdirSync(join(root, "site/downloads"));
	writeFileSync(join(root, "site/downloads/index.html"), "Download Clawdi\n");
	cpSync(join(root, "site"), join(root, "live"), { recursive: true });
	writeFileSync(join(root, "live/unrelated.html"), "Not generated by this publisher");
	const result = await prepare(root);
	expect(result.code).toBe(0);
	expect(result.output).toBe("changed=false\n");
	const requests = readFileSync(join(root, "requests"), "utf8").trim().split("\n");
	expect(new Set(requests).size).toBe(requests.length);

	for (const path of ["index.html", "desktop/latest-mac.yml", "downloads/index.html"]) {
		const original = readFileSync(join(root, "live", path));
		writeFileSync(
			join(root, "live", path),
			path.endsWith(".yml") ? `${original.toString()}# Changed\n` : "Changed content\n",
		);
		expect((await prepare(root)).output).toBe("changed=true\n");
		writeFileSync(join(root, "live", path), original);
	}
});

test("Pages deploys when a generated file returns 404, including first publication", async () => {
	const root = fixture();
	expect((await prepare(root)).code).toBe(0);
	expect((await prepare(root)).output).toBe("changed=true\n");
	cpSync(join(root, "site"), join(root, "live"), { recursive: true });
	for (const path of ["desktop/darwin-x64/beta-mac.yml", "index.html"]) {
		const original = readFileSync(join(root, "live", path));
		rmSync(join(root, "live", path));
		expect((await prepare(root)).output).toBe("changed=true\n");
		writeFileSync(join(root, "live", path), original);
	}
});

test("Pages deploys feed deletion for a pause and skips feeds already absent", async () => {
	const root = fixture();
	expect((await prepare(root)).code).toBe(0);
	cpSync(join(root, "site"), join(root, "live"), { recursive: true });
	expect((await prepare(root, "1.0.0,1.1.0-beta.2,1.1.0-beta.10")).code).toBe(0);
	expect((await prepare(root, "1.0.0,1.1.0-beta.2,1.1.0-beta.10")).output).toBe("changed=true\n");
	rmSync(join(root, "live/desktop"), { recursive: true });
	expect((await prepare(root, "1.0.0,1.1.0-beta.2,1.1.0-beta.10")).output).toBe("changed=false\n");
	// An omitted Windows feed is managed too, even though this release predates Windows.
	mkdirSync(join(root, "live/desktop/win32-arm64"), { recursive: true });
	writeFileSync(join(root, "live/desktop/win32-arm64/latest.yml"), "version: 1.0.0\n");
	expect((await prepare(root, "1.0.0,1.1.0-beta.2,1.1.0-beta.10")).output).toBe("changed=true\n");
});

test("Pages comparison fails closed on HTTP and transport errors, even after a change", async () => {
	const root = fixture();
	expect((await prepare(root)).code).toBe(0);
	for (const failure of ["503", "transport"]) {
		const result = await prepare(root, "", failure, "desktop/win32-x64/beta.yml");
		expect(result.code).not.toBe(0);
		expect(result.error).not.toBe("");
		expect(result.output).toBe("");
	}
});

test("Pages keeps both channels, paginates releases and selects semantic versions", async () => {
	const root = fixture();
	expect((await prepare(root)).code).toBe(0);
	for (const [file, version] of [
		["latest-mac.yml", "1.0.0"],
		["beta-mac.yml", "1.1.0-beta.10"],
	] as const) {
		const metadata = parse(readFileSync(join(root, "site/desktop", file), "utf8"));
		expect(metadata.version).toBe(version);
		expect(metadata.stagingPercentage).toBeUndefined();
		expect(metadata.files[0].url).toBe(
			`https://github.com/owner/repo/releases/download/desktop-v${version}/Clawdi.zip`,
		);
		expect(metadata.path).toBe(metadata.files[0].url);
		const intel = parse(readFileSync(join(root, "site/desktop/darwin-x64", file), "utf8"));
		expect(intel.version).toBe(version);
	}
});

test("all paused channels remove metadata, and regeneration is idempotent", async () => {
	const root = fixture();
	expect((await prepare(root)).code).toBe(0);
	const previous = readFileSync(join(root, "site/desktop/latest-mac.yml"), "utf8");
	expect((await prepare(root)).code).toBe(0);
	expect(readFileSync(join(root, "site/desktop/latest-mac.yml"), "utf8")).toBe(previous);
	expect((await prepare(root, "1.0.0,1.1.0-beta.2,1.1.0-beta.10")).code).toBe(0);
	expect(existsSync(join(root, "site/desktop/latest-mac.yml"))).toBe(false);
	expect(existsSync(join(root, "site/desktop/beta-mac.yml"))).toBe(false);
});

